def main():
    problems = Problem.objects.filter(contest_id=365).order_by('_id')
    updated = 0
    skipped = 0
    not_found = []

    for p in problems:
        if p._id in TITLE_MAP:
            new_title = TITLE_MAP[p._id]
            if p.title != new_title:
                print(f'  {p._id}: "{p.title}" -> "{new_title}"')
                p.title = new_title
                p.save(update_fields=['title'])
                updated += 1
            else:
                skipped += 1
        else:
            not_found.append(p._id)

    if not_found:
        print(f'\nWARNING: {len(not_found)} problems not in TITLE_MAP:')
        for pid in not_found:
            print(f'  {pid}')

    print(f'\nDone: {updated} updated, {skipped} already matched, total {problems.count()}')

if __name__ == '__main__':
    main()
